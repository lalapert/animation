"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Void Mart 6 "Employee of the Month": 36 frames of the security camera; Pip runs for it. Script: channel/scripts/VM06_employee_of_the_month.md
"""
import json, os, re
TAGS = re.compile(r"\[[^\]]*\]\s*")              # eleven_v4 audio tags: direction, never shown

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 120.0
BEAT = 60.0 / BPM
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
order = [l["id"] for l in cfg["lines"]]
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
SUBCOL = {"PIP": "#5fe3cc", "RAE": "#ffb066", "MAGS": "#ff7d8c"}
# pause before each line (comic timing). L5 waits for Pip's restock run; L11 for Rae's walk to the ballot box; L13 for the flash and the photo
RAE_STEP, RAE_SPS = 160, 1.9
RAEB = (2250 - 1760) / (RAE_STEP * RAE_SPS)                                                   # Rae's walk back in, seconds
GAP = {"L1": 1.5, "L2": 0.4, "L3": 0.35, "L4": 0.4, "L5": 4.2, "L6": 0.3, "L7": 0.35, "L8": 0.9, "L9": 0.35, "L10": 0.5,
       "L11": round(.35 + RAEB + .05 + .5 + .35, 3), "L12": 0.6, "L13": 2.2}
VO, t, T = [], 0.0, {}
W = lambda k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["words"]
for k in order:
    start = t + GAP[k]
    if k == "L5": T["MONT0"] = round(t + 0.35, 3)                                             # the restock run starts after "never takes a break"
    if k == "L11": T["RAEB0"] = round(t + 0.35, 3)                                            # Rae walks back in from the right
    d = durs[k]
    VO.append({"id": k, "who": lines[k]["who"], "t": round(start, 3), "dur": d, "sub": lines[k].get("sub", TAGS.sub("", lines[k]["text"]).strip()),
               "col": SUBCOL[lines[k]["who"]], "gain_db": lines[k].get("gain_db", 0)})
    t = start + d
END_BEAT = 3.2
DUR = round(t + END_BEAT, 2)
for i, v in enumerate(VO):
    v["s0"] = round(max(0.0, v["t"] - 0.08), 3)
    nxt = VO[i + 1]["t"] - 0.12 if i + 1 < len(VO) else DUR - 0.3
    v["s1"] = round(min(nxt, max(v["t"] + v["dur"] + 0.45, v["s0"] + 1.0)), 3)
    assert v["s1"] >= v["t"] + v["dur"] - 0.05, v["id"]
for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"])
assert 38 <= DUR <= 60, DUR
V = {v["id"]: v for v in VO}
end = lambda k: V[k]["t"] + V[k]["dur"]
w1 = W("L1"); T["ME"] = round(V["L1"]["t"] + [x for x in w1 if x["w"].lower().startswith("me")][-1]["t0"] - 0.12, 3)   # the big hop on "ME!"
T["RAEIN0"] = round(V["L2"]["t"] - (2250 - 1840) / (RAE_STEP * RAE_SPS) - 0.2, 3)                                    # Rae walks in from the right, arrives before her line
T["RUN0"], T["RUN1"] = round(T["MONT0"] + 0.25, 3), round(V["L5"]["t"] - 0.35, 3)                                     # Pip's restock run along the aisle
T["ARRIVE"] = round(T["RAEB0"] + RAEB, 3); T["SLIP"] = round(T["ARRIVE"] + 0.55, 3)                                 # the ballot goes in
w8 = W("L8"); T["SCORE"] = round(V["L8"]["t"] + [x for x in w8 if x["w"].lower().startswith("mags")][0]["t0"] - 0.1, 3)  # the scoreboard numbers
T["FLASH"] = round(end("L12") + 0.15, 3); T["DROP"] = round(T["FLASH"] + 0.45, 3); T["PHOTO1"] = round(T["FLASH"] + 1.9, 3)
T["MAGSTURN"] = round(V["L4"]["t"] + 0.02, 3)                                                                       # 11/13: MAGS turns to Pip on his first close-up (the servo)
T["JUMP"] = round(T["FLASH"] - 0.35, 3)                                                                             # Pip jumps into the picture
SHOTS = [
    ["OPEN", 0.0, V["L3"]["t"]],
    ["PIP_CU", V["L3"]["t"], V["L4"]["t"]],
    ["MAGS_CU", V["L4"]["t"], T["MONT0"]],
    ["MONTAGE", T["MONT0"], V["L5"]["t"] - .1],
    ["MAGS_MED", V["L5"]["t"] - .1, V["L6"]["t"]],
    ["PIP_CU", V["L6"]["t"], V["L7"]["t"]],
    ["MAGS_CU", V["L7"]["t"], V["L8"]["t"] - .1],
    ["WIDE_VOTE", V["L8"]["t"] - .1, V["L9"]["t"]],
    ["PIP_CU", V["L9"]["t"], V["L10"]["t"]],
    ["MAGS_CU", V["L10"]["t"], end("L10") + .3],
    ["WIDE_VOTE", end("L10") + .3, V["L11"]["t"]],
    ["RAE_MED", V["L11"]["t"], V["L12"]["t"]],
    ["WIDE_FLASH", V["L12"]["t"], T["FLASH"]],
    ["PHOTO", T["FLASH"], T["PHOTO1"]],
    ["END_WALL", T["PHOTO1"], DUR],
]
SHOTS = [[n, round(a, 3), round(b, 3)] for n, a, b in SHOTS]
for a, b in zip(SHOTS, SHOTS[1:]):
    assert abs(a[2] - b[1]) < 1e-6 and a[2] > a[1], (a, b)
TL = {"BPM": BPM, "BEAT": BEAT, "BAR": 4 * BEAT, "DUR": DUR, "VO": VO, "SHOTS": SHOTS, **T}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
CH = {k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["chars"] for k in V}
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\nwindow.CHARS = " + json.dumps(CH) + ";\n")
print("DUR", DUR, T)
for v in VO:
    print(f'{v["id"]:4} {v["who"]:5} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
for s in SHOTS: print(f'  {s[0]:12s} {s[1]:6.2f}-{s[2]:6.2f}')
