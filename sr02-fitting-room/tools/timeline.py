"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Tape 2 "Fitting Room 3": CCTV 09 watches the fitting rooms in Fashion 99 while the PA closes them.
Stall 3 is lit and occupied from the first frame: one pair of feet under the curtain, heels to the camera.
Every glitch, one more pair. After "Your time is up." they all turn around. Then someone knocks from inside.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
START = {"L1": 2.4, "L2": 8.6, "L3": 19.6}
VO = []
for k in ["L1", "L2", "L3"]:
    VO.append({"id": k, "who": "PA", "t": START[k], "dur": durs[k], "sub": lines[k].get("sub", lines[k]["text"]), "col": "#f2f2f2", "fx": "pa"})
for i, v in enumerate(VO):
    v["s0"] = round(v["t"] - 0.05, 3)
    nxt = VO[i + 1]["t"] - 0.15 if i + 1 < len(VO) else 99
    v["s1"] = round(min(nxt, v["t"] + v["dur"] + 0.6), 3)
for a, b in zip(VO, VO[1:]):
    assert a["t"] + a["dur"] < b["t"] - 0.3, (a["id"], b["id"])
CHIME = 1.1
# [time, pairs of feet under the curtain]; each step hides behind a glitch
STEPS = [[0.0, 1], [6.6, 2], [12.2, 3], [16.4, 4], [23.2, 5], [26.4, 6]]
GLITCH = [[s[0] - .18, .42] for s in STEPS[1:]]
TURN = 29.4                # no glitch: on the next CCTV frame every pair faces the camera; the hum cuts
KNOCKS = [31.0, 31.75, 32.5]
SLIDE = 33.2               # the curtain rings slide a few centimetres
END = 34.0
DUR = 35.6
STATIC = [[0.0, 0.6], [END, DUR]]
assert 30 <= DUR <= 50
assert all(not (g[0] < v["t"] + v["dur"] and g[0] + g[1] > v["t"]) for g in GLITCH for v in VO), "a glitch lands on a PA line"
TL = {"DUR": DUR, "VO": VO, "CHIME": CHIME, "STEPS": STEPS, "GLITCH": GLITCH, "TURN": TURN, "KNOCKS": KNOCKS, "SLIDE": SLIDE,
      "STATIC": STATIC, "END": END,
      "LABEL": "TAPE 0002", "SUB": "CAM 09  ·  FASHION 99  ·  12/31/99", "RULE": "RULE 2: IF A FITTING ROOM IS OCCUPIED,\nDO NOT KNOCK.",
      "STAMP0": [23, 44, 10], "CAM": "CAM 09", "PLACE": "FASHION 99",
      "EGG": {"t": 16.5, "dur": 0.1, "what": "the stall plate over fitting room 3 reads 7 for six frames"}}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\n")
print("DUR", DUR)
for v in VO: print(f'{v["id"]} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f} sub {v["s0"]:6.2f}-{v["s1"]:6.2f} {v["sub"]!r}')
