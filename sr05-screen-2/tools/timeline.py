"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Tape 5 "Screen 2": the cinema's CCTV multiplexer switches between CAM 12 (Screen 2, closed) and CAM 11 (the lobby).
The screen in Screen 2 is on and shows the lobby camera. The real lobby is empty; on the screen, someone stands in it,
closer each time. Then the screen shows Screen 2 itself, with someone in row G. Then the real row G: a head, which turns
round to the camera. Script: channel/scripts/SR05_screen_2.md
v2 (owner 11/12 "not scary; more care for direction, camera moves, transitions, sound"; reference tape 6 v3):
darker, a flickering projector, the archivist's playback zoom pushing further into the screen at every return, the figure on
the screen still and then one held-frame jerk forward, arms longer each time, a dead-quiet lobby, and an ending on grotesque
movement only (no jump at the lens): the head in row G turns round in held 6 fps steps, a creak on each, then snaps the rest
of the way; the projector dies; a long near-silent hold; static.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
START = {"L1": 3.2, "L2": 21.0, "L3": 30.0}
VO = []
for k in ["L1", "L2", "L3"]:
    VO.append({"id": k, "who": lines[k]["who"], "t": START[k], "dur": durs[k], "sub": lines[k].get("sub", lines[k]["text"]), "col": "#f2f2f2", "fx": "pa"})
for i, v in enumerate(VO):
    v["s0"] = round(v["t"] - 0.05, 3)
    nxt = VO[i + 1]["t"] - 0.15 if i + 1 < len(VO) else 99
    v["s1"] = round(min(nxt, v["t"] + v["dur"] + 0.6), 3)
fr = lambda k: round(k / 6, 4)                 # CCTV frame k (6 fps): every move happens on a frame boundary
# the multiplexer: [camera, start, end, stage]. A = CAM 12 Screen 2, L = CAM 11 lobby.
# stage on A: what the screen shows (1-3 the lobby with the figure far, middle, under the camera; 4 Screen 2 itself with
# someone in row G; 5 the screen is blank light and the real row G is not empty). On L: 'l1', 'l2' empty, 'open' the Screen 2
# door open, closing by itself.
SEGS = [["A", 0.6, 6.0, 1], ["L", 6.0, 10.0, "l1"], ["A", 10.0, 16.0, 2], ["L", 16.0, 19.5, "l2"], ["A", 19.5, 26.0, 3],
        ["L", 26.0, 28.0, "open"], ["A", 28.0, 32.9, 4], ["A", 33.15, 40.8, 5]]
SWITCHES = [6.0, 10.0, 16.0, 19.5, 26.0]       # multiplexer clicks (28.0 is a tracking roll)
ROLL = [28.0, 28.35]
BLACK = [32.9, 33.15]                          # a tear, then a few frames of black and dead sound before the real row G
GLITCH = [[t - .06, .2] for t in SWITCHES] + [[32.72, .18]]
# the playback zoom for each segment: [z0, z1] over the segment (A5 is special: a crash zoom onto the head)
ZOOM = [[1.0, 1.22], [1.0, 1.1], [1.18, 1.5], [1.0, 1.12], [1.45, 1.9], [1.0, 1.14], [1.0, 1.3], [1.0, 1.0]]
JERKS = [fr(32), fr(88), fr(147)]              # the figure on the screen jumps forward in one frame (5.33, 14.67, 24.5)
DOOR = 26.25                # the Screen 2 door swings shut by itself
SEAT = 28.7                 # a seat goes down in the real room (row G is empty)
CRASH = [34.0, 34.1]        # crash zoom onto the head
TURN0 = 207                 # CCTV frame of the first head step (34.5 s)
HEAD = [[fr(TURN0 + k), a] for k, a in [(0, 10), (2, 21), (4, 33), (7, 46), (9, 58), (11, 70), (13, 83), (15, 96), (17, 110)]]
SNAP = fr(TURN0 + 22)       # then it holds, and the rest of the way in one frame (38.17)
PROJ_DIE = 38.5             # the projector dies: the hum winds down, the light sinks
BREATH = 39.7
QUIET = BLACK[0]            # music gone at the black frames
END = 40.8
DUR = 41.8
STATIC = [[0.0, 0.6], [END, DUR]]
assert 30 <= DUR <= 50
TL = {"DUR": DUR, "VO": VO, "SEGS": SEGS, "SWITCHES": SWITCHES, "ROLL": ROLL, "BLACK": BLACK, "GLITCH": GLITCH, "ZOOM": ZOOM,
      "JERKS": JERKS, "DOOR": DOOR, "SEAT": SEAT, "CRASH": CRASH, "HEAD": HEAD, "SNAP": SNAP, "PROJ_DIE": PROJ_DIE, "BREATH": BREATH,
      "QUIET": QUIET, "STATIC": STATIC, "END": END,
      "LABEL": "TAPE 0005", "SUB": "CAM 11 / CAM 12  ·  HALLOWAY CINEMA  ·  12/31/99",
      "RULE": "RULE 5: IF A SCREEN TURNS ON\nBY ITSELF, DO NOT WATCH IT.",
      "STAMP0": [23, 52, 6],
      "EGG": {"t": 17.0, "dur": 0.1, "what": "the sign over the Screen 2 doors in the lobby reads 6 for six frames"}}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\n")
print("DUR", DUR)
for v in VO: print(f'{v["id"]} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f} sub {v["s0"]:6.2f}-{v["s1"]:6.2f} {v["sub"]!r}')
print("head steps", [h[0] for h in HEAD], "snap", SNAP)
