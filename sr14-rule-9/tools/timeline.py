"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Tape 14 "Rule 9": Leon Marsh, December 9, 1999, 2:10 A.M., the guard office. On the wall by the desk lamp, the night-shift
rule sheet: eight typed rules, and under them a ninth in blue ballpoint, big: "9. KEEP WRITING." His camcorder compares it with
his own night log: the same hand, the same curly E (his: written like a backwards 3). CAM 02 (the office from the corner):
him at the desk; by the corkboard, very dark, something tall. He writes "I DID NOT WRITE IT"; the pen does not stop: "KEEP
WRITING", again and again, bigger and faster; "Stop. Stop." It stops dead. Then his hand rips the pen down across both pages
and tears them (the one loud sound), and stays there, the wrist bent too far. CAM 02: it stands bent over his chair, its long
arm over his shoulder, its hand on his hand on the pen. Scare type: HIS OWN HAND (his body does it; the camera that is his
eyes never sees the other hand). The end loops to frame 1, the sheet.
Script: channel/scripts/SR14_rule_9.md
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
START = {"L1": 3.8, "L2": 8.4, "L3": 10.7, "L4": 20.6}
GAIN = {"L1": -2.0, "L2": -2.5, "L3": -3.0, "L4": -0.5}
VO = []
for k in ["L1", "L2", "L3", "L4"]:
    VO.append({"id": k, "who": lines[k]["who"], "t": START[k], "dur": durs[k], "sub": lines[k].get("sub", lines[k]["text"]), "col": "#f2f2f2",
               "fx": "cam", "pos": "top", "gain_db": GAIN.get(k, 0.0)})

# ---------------------------------------------------------------- shots: cam1 / cam2 are Leon's camcorder (colour, hand-held);
# cctv1-2 are CAM 02 (the office from its corner), played back by the archive (6 frames a second)
END = 33.0
DUR = 34.0
SHOTS = [["cam1", 0.0, 13.4], ["cctv1", 13.4, 15.6], ["cam2", 15.6, 25.2], ["cctv2", 25.2, END]]
RECCUT = []
OPEN = {"on": True, "full": 3.0, "end": 3.6}   # owner 11/20 test (tape 8): the first 3 s fill the 9:16 frame; "on": False switches it off
TO_LOG = [7.3, 8.4]          # the camcorder tilts down from the sheet to his night log
EGG = {"t": 9.4, "dur": 0.1, "what": "the night log's printed page number 9 reads 14 for six frames"}
TO_SHEET = [10.3, 10.95]     # up to the sheet again (compare)
BACK_LOG = [12.2, 13.1]
# his writing on the right-hand page: [text, start, end]; the last one stops dead at QUIET[0]
WRITES = [["I DID NOT WRITE IT", 16.0, 19.0], ["KEEP WRITING", 19.15, 20.9], ["KEEP WRITING", 20.95, 22.05],
          ["KEEP WRITING", 22.1, 22.75], ["KEEP WRITING", 22.8, 23.42]]
QUIET = [23.05, 23.55]       # the pen stops dead, lifted; near silence
STING = 23.55                # the hand rips the pen down across both pages
RIP = [23.55, 23.72]
BEND = [23.72, 24.0]         # and stays there, the wrist bent too far
RECOIL = [24.35, 25.0]       # he jerks back from the desk
PUSH2 = [26.0, 29.0]         # CAM 02: the playback zooms in on its hand on his
STATIC = [[END, DUR]]        # no static before frame 1: the tape opens on the rule sheet (the loop comes back to it)
GLITCH = [[END - .3, .3]]
ASK = "KEEP WRITING OR RIP THE PAGE?"
ASK_T = round(DUR - 2.5, 3)  # owner 11/16: the last 2.5 s carry the two-choice question under the rule card
assert 30 <= DUR <= 50
for i, v in enumerate(VO):
    v["s0"] = round(v["t"] - 0.05, 3)
    nxt = VO[i + 1]["t"] - 0.15 if i + 1 < len(VO) else 99
    cut = min([c for c in RECCUT + [s[2] for s in SHOTS] if c > v["t"]], default=99) - .06    # never across a cut
    v["s1"] = round(min(nxt, v["t"] + v["dur"] + 0.5, cut), 3)
    assert v["t"] + v["dur"] < nxt + .15, v["id"]
    assert v["t"] + v["dur"] - .05 < cut + .06, v["id"]
assert VO[3]["t"] + VO[3]["dur"] < QUIET[0] + .1
TL = {"DUR": DUR, "VO": VO, "SHOTS": SHOTS, "RECCUT": RECCUT, "OPEN": OPEN, "TO_LOG": TO_LOG, "EGG": EGG, "TO_SHEET": TO_SHEET,
      "BACK_LOG": BACK_LOG, "WRITES": WRITES, "QUIET": QUIET, "STING": STING, "RIP": RIP, "BEND": BEND, "RECOIL": RECOIL,
      "PUSH2": PUSH2, "END": END, "STATIC": STATIC, "GLITCH": GLITCH, "ASK": ASK, "ASK_T": ASK_T,
      "LABEL": "TAPE 0014", "SUB": "CAMCORDER / CAM 02  ·  GUARD OFFICE  ·  12/09/99",
      "RULE": "RULE 14: THERE ARE ONLY EIGHT RULES.\nDO NOT FOLLOW THE NINTH.",
      "STAMP1": [2, 11, 4], "STAMP2": [2, 12, 31], "DATE": "12-09-1999"}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\n")
print("DUR", DUR)
for v in VO: print(f'{v["id"]} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f} sub {v["s0"]:6.2f}-{v["s1"]:6.2f} {v["sub"]!r}')
