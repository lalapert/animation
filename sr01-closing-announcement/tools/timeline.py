"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Tape 1 "Closing Announcement": CCTV 01 watches the main concourse while the PA closes the mall.
Something stands under the far EXIT sign from the first frame; it is closer every time the picture glitches.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
START = {"L1": 3.0, "L2": 8.2, "L3": 12.6, "L4": 18.4, "L5": 26.6, "L6": 30.4}
VO = []
for k in ["L1", "L2", "L3", "L4", "L5", "L6"]:
    VO.append({"id": k, "who": "PA", "t": START[k], "dur": durs[k], "sub": lines[k].get("sub", lines[k]["text"]), "col": "#f2f2f2", "fx": "pa"})
for i, v in enumerate(VO):
    v["s0"] = round(v["t"] - 0.05, 3)
    nxt = VO[i + 1]["t"] - 0.15 if i + 1 < len(VO) else 99
    v["s1"] = round(min(nxt, v["t"] + v["dur"] + 0.6), 3)
for a, b in zip(VO, VO[1:]):
    assert a["t"] + a["dur"] < b["t"] - 0.3, (a["id"], b["id"])
CHIME = 1.2
# the figure: (time it appears there, distance down the concourse in metres); each jump hides behind a glitch
JUMPS = [[0.0, 34.6, 0.0], [4.4, 11.3, 1.6], [11.0, -1, 0], [16.9, 9.0, -.6], [22.4, 7.4, .6], [25.2, 6.2, 1.6], [29.0, 5.0, 2.4], [32.6, 3.3, 3.0]]   # [time, z, x]; z < 0: gone. The first step (4.4 s) lands in the pause after "Attention shoppers."
GLITCH = [[j[0] - .18, .42] for j in JUMPS[1:]]
END = 34.6                 # static burst; the tape ends
DUR = 36.4
STATIC = [[0.0, 0.7], [END, DUR]]
assert 30 <= DUR <= 50
TL = {"DUR": DUR, "VO": VO, "CHIME": CHIME, "JUMPS": JUMPS, "GLITCH": GLITCH, "STATIC": STATIC, "END": END,
      "LABEL": "TAPE 0001", "SUB": "CAM 01  ·  MAIN CONCOURSE  ·  12/31/99", "RULE": "RULE 1: WHEN THE CLOSING\nANNOUNCEMENT PLAYS, LEAVE.",
      "STAMP0": [23, 58, 3], "CAM": "CAM 01", "PLACE": "MAIN CONCOURSE",
      "EGG": {"t": 16.9, "dur": 0.1, "what": "OSD reads CAM 13 for six frames"}}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\n")
print("DUR", DUR)
for v in VO: print(f'{v["id"]} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f} sub {v["s0"]:6.2f}-{v["s1"]:6.2f} {v["sub"]!r}')
