"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 72.0
BEAT = 60.0 / BPM          # 0.8333 s
BAR = 4 * BEAT             # 3.3333 s
DUR = 90.0
LRAD = 38                  # ripe lemon radius (film.js LR)


def bar(n, beat=1.0):
    """time of bar n (1-based), beat (1-based, may be fractional)"""
    return round((n - 1) * BAR + (beat - 1) * BEAT, 4)


lines = {l["id"]: l for l in json.load(open(os.path.join(HERE, "voice", "lines.json")))["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))

# narration start times (placed against the cue grid; see TREATMENT.md section 9)
START = {
    "L1": 1.50,
    "L2": 8.30,
    "L3": 14.40,
    "L4": bar(8) - 0.86,     # "twenty-three" lands on the flower burst (bar 8, beat 1)
    "L5": 31.00,
    "L6": 38.90,             # "go." at ~41.7 s, just before the first fruit lands
    "L7": 44.20,
    "L8": 51.60,
    "L9": bar(20) - 2.69,    # "gold." lands on the second glaze (bar 20, beat 1)
    "L10": 67.40,
    "L11": 76.00,
    "L12": bar(25) - 1.09,   # "bud." lands on the new bud (bar 25, beat 1)
}

VO = []
for k in ["L%d" % i for i in range(1, 13)]:
    t, d = START[k], durs[k]
    t0 = round(t - 0.15, 3)
    t1 = round(max(t + d + 0.45, t0 + 1.8, t + d + 0.6), 3)
    VO.append({"id": k, "t": round(t, 3), "dur": d, "sub": lines[k]["sub"], "s0": t0, "s1": t1})

for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"], a["s1"], b["s0"])

TL = {
    "BPM": BPM, "BEAT": BEAT, "BAR": BAR, "DUR": DUR,
    "VO": VO,
    "HOOK_MIST": [6.5, 7.6],          # hook erased to paper
    "JAN": 7.6,                        # January starts painting
    "MONTHS": [                        # header + sky change times
        [7.6, 1], [bar(5), 3], [bar(7), 4], [bar(10), 5], [bar(12), 6],
        [bar(16), 7], [55.0, 8], [bar(19), 9], [bar(20), 10], [bar(21), 11], [bar(22), 12],
    ],
    "BUDS": [bar(5, 1.5), bar(6, 4)],  # 23 buds appear on the eighth-note grid
    "BURST": bar(8),                   # 23 flowers
    "PETALS": [bar(10), bar(10) + 2.2],
    "FRUITLETS": [bar(10) + 0.6, bar(10) + 2.6],
    "SILENCE1": bar(12),               # music out (June)
    "DROPS": [round(bar(13, 4) + k * BEAT, 4) for k in range(8)],   # landing times, on the beat
    "PIANO_BACK": bar(15, 3),
    "RAIN": [bar(16), 55.6],
    "GROW": [[bar(15, 3), 8], [55.0, 14], [bar(19), 24], [bar(21), 32], [bar(22), LRAD]],
    "GLAZE": [bar(19), bar(20), bar(21), bar(22)],
    "TEA_MIST": [72.6, 73.6],
    "NIGHT": [73.7, 74.9],
    "SILENCE2": [bar(23), bar(24)],
    "CUP": bar(23, 3),
    "NEWBUD": bar(25),
    "PAGE": bar(26),
    "TITLE": [85.0, 86.0],
}

os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\n")
for v in VO:
    print(f'{v["id"]:4} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
print("drops", TL["DROPS"])
