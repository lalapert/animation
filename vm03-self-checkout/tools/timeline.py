"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Void Mart 3 "Self-Checkout": corporate sends a self-checkout kiosk that is more deadpan than Rae.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 120.0
BEAT = 60.0 / BPM
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
order = [l["id"] for l in cfg["lines"]]
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
SUBCOL = {"PIP": "#5fe3cc", "RAE": "#ffb066", "MAGS": "#ff7d8c", "KIOSK": "#9fe6ff"}
# pause before each line (comic timing); the blob's moves and the plug get their own room below
GAP = {"L1": 0.6, "L2": 0.35, "L3": 0.3, "L4": 0.45, "L5": 1.9, "L6": 0.75, "L7": 0.85, "L8": 0.4, "L9": 0.45,
       "L10": 2.3, "L11": 0.3, "L12": 0.45}
VO, t, T = [], 0.0, {}
for k in order:
    start = t + GAP[k]
    if k == "L5": T["DOOR"] = round(t + 0.25, 3); T["PLOP"] = round(start - 0.45, 3)     # the blob comes in and sits in the bagging area
    if k == "L6": T["OFF"] = round(t + 0.15, 3)                                           # it scoots off
    if k == "L7": T["ON"] = round(t + 0.2, 3)                                             # and back on
    if k == "L10": T["STARE"] = round(t + 0.1, 3); T["PLUG"] = round(t + 1.05, 3); T["DARK"] = round(t + 1.5, 3)
    d = durs[k]
    VO.append({"id": k, "who": lines[k]["who"], "t": round(start, 3), "dur": d, "sub": lines[k].get("sub", lines[k]["text"]),
               "col": SUBCOL[lines[k]["who"]], "gain_db": lines[k].get("gain_db", 0), **({"fx": "speaker"} if lines[k]["who"] == "KIOSK" else {})})
    t = start + d
END_BEAT = 3.0
DUR = round(t + END_BEAT, 2)
for i, v in enumerate(VO):
    v["s0"] = round(max(0.0, v["t"] - 0.08), 3)
    nxt = VO[i + 1]["t"] - 0.12 if i + 1 < len(VO) else DUR - 0.3
    v["s1"] = round(min(nxt, max(v["t"] + v["dur"] + 0.45, v["s0"] + 1.0)), 3)
    assert v["s1"] >= v["t"] + v["dur"] - 0.05, v["id"]
for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"])
assert 40 <= DUR <= 60, DUR
V = {v["id"]: v for v in VO}
end = lambda k: V[k]["t"] + V[k]["dur"]
T["FLIP"] = round(V["L12"]["t"] + V["L12"]["dur"] + 0.15, 3)   # the incident counter goes back to 0, after the line
SHOTS = [
    ["WIDE_KIOSK", 0.0, V["L1"]["t"] + 2.4],
    ["KIOSK_CU", V["L1"]["t"] + 2.4, V["L2"]["t"]],
    ["RAE_CU", V["L2"]["t"], V["L3"]["t"]],
    ["MAGS_CU", V["L3"]["t"], V["L4"]["t"]],
    ["PIP_CU", V["L4"]["t"], T["DOOR"]],
    ["WIDE_DOOR", T["DOOR"], V["L5"]["t"]],
    ["KIOSK_CU", V["L5"]["t"], T["OFF"]],
    ["KIOSK_MED", T["OFF"], V["L8"]["t"]],
    ["PIP_CU", V["L8"]["t"], V["L9"]["t"]],
    ["KIOSK_ALERT", V["L9"]["t"], T["STARE"]],
    ["RAE_CU", T["STARE"], T["PLUG"] - .35],
    ["SOCKET_CU", T["PLUG"] - .35, T["DARK"]],
    ["KIOSK_CU", T["DARK"], V["L10"]["t"]],
    ["RAE_MED", V["L10"]["t"], V["L11"]["t"]],
    ["PIP_CU", V["L11"]["t"], V["L12"]["t"]],
    ["MAGS_CU", V["L12"]["t"], T["FLIP"] - .1],
    ["BOARD", T["FLIP"] - .1, T["FLIP"] + .9],
    ["WIDE_END", T["FLIP"] + .9, DUR],
]
SHOTS = [[n, round(a, 3), round(b, 3)] for n, a, b in SHOTS]
for a, b in zip(SHOTS, SHOTS[1:]):
    assert abs(a[2] - b[1]) < 1e-6 and a[2] > a[1], (a, b)
TL = {"BPM": BPM, "BEAT": BEAT, "BAR": 4 * BEAT, "DUR": DUR, "VO": VO, "SHOTS": SHOTS, **T}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
CH = {k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["chars"] for k in V}
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\nwindow.CHARS = " + json.dumps(CH) + ";\n")
print("DUR", DUR, {k: T[k] for k in T})
for v in VO:
    print(f'{v["id"]:4} {v["who"]:5} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
for s in SHOTS: print(f'  {s[0]:12s} {s[1]:6.2f}-{s[2]:6.2f}')
