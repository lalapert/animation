"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Volt Labs 1 "Day One": the Adoration Ray. Cleo fires it early; only pigeons answer.
"""
import json, os, re
TAGS = re.compile(r"\[[^\]]*\]\s*")              # eleven_v4 audio tags: direction, never shown

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 132.0
BEAT = 60.0 / BPM
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
order = [l["id"] for l in cfg["lines"]]
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
SUBCOL = {"VERA": "#d8ff7a", "CLEO": "#c9b8ff"}
W6 = json.load(open(os.path.join(HERE, "voice", "out", "L6.json")))["words"]
THREE = [w for w in W6 if w["w"].lower().startswith("three")][0]["t0"]   # where "Three..." starts in this take
CUT = {"L6": round(THREE + .5, 3)}     # Cleo fires during "Three...": the line is cut off by the zap
# pause before each line (comic timing); the big beats get their own room below
GAP = {"L1": 0.9, "L2": 0.35, "L3": 0.3, "L4": 0.5, "L5": 0.4, "L6": 0.35, "L7": 1.3, "L8": 0.3, "L9": 2.1, "L10": 0.35,
       "L11": 0.3, "L12": 0.9, "L13": 1.25, "L14": 0.35, "L15": 0.8}
VO, t, T = [], 0.0, {}
for k in order:
    if k == "L9":                      # after "You were taking forever.": silence, one pigeon, then the flood
        T["WIN"] = round(t + 0.4, 3); T["LAND"] = round(t + 0.75, 3); T["FLOOD"] = round(t + 2.0, 3)
        t = T["FLOOD"]
    if k == "L12": T["FRY"] = round(t + 0.15, 3)
    if k == "L13": T["BOARDT"] = round(t + 0.25, 3)
    if k == "L15": T["CAPT"] = round(t + 0.35, 3)
    start = t + GAP[k]
    d = CUT.get(k, durs[k])
    VO.append({"id": k, "who": lines[k]["who"], "t": round(start, 3), "dur": d, "sub": lines[k].get("sub", TAGS.sub("", lines[k]["text"]).strip()),
               "col": SUBCOL[lines[k]["who"]], "gain_db": lines[k].get("gain_db", 0), **({"cut": d} if k in CUT else {})})
    t = start + d
    if k == "L6":
        T["PRESS"] = round(start + THREE + .2, 3); T["FIRE"] = round(start + THREE + .45, 3)
END_BEAT = 1.7
DUR = round(t + END_BEAT, 2)
for i, v in enumerate(VO):
    v["s0"] = round(max(0.0, v["t"] - 0.08), 3)
    nxt = VO[i + 1]["t"] - 0.12 if i + 1 < len(VO) else DUR - 0.3
    v["s1"] = round(min(nxt, max(v["t"] + v["dur"] + 0.45, v["s0"] + 1.0)), 3)
    assert v["s1"] >= v["t"] + v["dur"] - 0.05, v["id"]
for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"])
assert 40 <= DUR <= 62, DUR
V = {v["id"]: v for v in VO}
end = lambda k: V[k]["t"] + V[k]["dur"]
SHOTS = [
    ["WIDE_IN", 0.0, V["L2"]["t"]],
    ["CLEO_CU", V["L2"]["t"], V["L3"]["t"]],
    ["VERA_CU", V["L3"]["t"], V["L4"]["t"]],
    ["RAY_SHOT", V["L4"]["t"], V["L4"]["t"] + 3.25],
    ["VERA_SCHEME", V["L4"]["t"] + 3.25, V["L5"]["t"]],
    ["CLEO_CU", V["L5"]["t"], V["L6"]["t"]],
    ["VERA_COUNT", V["L6"]["t"], T["PRESS"] - .35],
    ["CLEO_PRESS", T["PRESS"] - .35, T["FIRE"]],
    ["WIDE_FIRE", T["FIRE"], V["L7"]["t"]],
    ["VERA_CU", V["L7"]["t"], V["L8"]["t"]],
    ["CLEO_CU", V["L8"]["t"], T["WIN"]],
    ["WINDOW", T["WIN"], T["FLOOD"]],
    ["WIDE_FLOOD", T["FLOOD"], V["L9"]["t"]],
    ["VERA_MED_P", V["L9"]["t"], V["L10"]["t"]],
    ["CLEO_CU", V["L10"]["t"], V["L11"]["t"]],
    ["VERA_MED_P", V["L11"]["t"], V["L12"]["t"]],
    ["VERA_CU_P", V["L12"]["t"], T["BOARDT"]],
    ["BOARD", T["BOARDT"], V["L14"]["t"]],
    ["WIDE_ARMY", V["L14"]["t"], T["CAPT"] - .25],
    ["BENCH_CU", T["CAPT"] - .25, V["L15"]["t"]],
    ["CLEO_END", V["L15"]["t"], DUR],
]
SHOTS = [[n, round(a, 3), round(b, 3)] for n, a, b in SHOTS]
for a, b in zip(SHOTS, SHOTS[1:]):
    assert abs(a[2] - b[1]) < 1e-6 and a[2] > a[1], (a, b)
TL = {"BPM": BPM, "BEAT": BEAT, "BAR": 4 * BEAT, "DUR": DUR, "VO": VO, "SHOTS": SHOTS, **T}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
CH = {k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["chars"] for k in V}
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\nwindow.CHARS = " + json.dumps(CH) + ";\n")
print("DUR", DUR, {k: T[k] for k in T})
for v in VO:
    print(f'{v["id"]:4} {v["who"]:4} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
for s in SHOTS: print(f'  {s[0]:12s} {s[1]:6.2f}-{s[2]:6.2f}')
