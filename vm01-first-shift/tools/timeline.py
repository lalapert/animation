"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Lines follow each other with the gaps below (comic timing); shots and events hang off the line times.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 120.0
BEAT = 60.0 / BPM
BAR = 4 * BEAT
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
SUBCOL = {"PIP": "#5fe3cc", "RAE": "#ffb066", "MAGS": "#ff7d8c"}

# gap before each line (s): comic timing
GAP = {"L1": 2.0, "L2": 0.25, "L3": 0.5, "L4": 0.3, "L5": 0.25, "L6": 2.4, "L7": 0.6, "L8": 1.2, "L9": None, "L10": 0.6, "L11": 0.5}
VO, t = [], 0.0
T = {}
for k in [l["id"] for l in cfg["lines"]]:
    if k == "L9":
        T["FREEZE"] = [round(t + 0.2, 3), round(t + 2.8, 3)]      # grin freezes, Rae sips
        T["MONSTER"] = round(t + 2.8, 3)                          # chime, flicker, shadow
        start = T["MONSTER"] + 2.0
    elif k == "L1":
        start = GAP[k]
    else:
        start = t + GAP[k]
    d = durs[k]
    VO.append({"id": k, "who": lines[k]["who"], "t": round(start, 3), "dur": d, "sub": lines[k].get("sub", lines[k]["text"]),
               "col": SUBCOL[lines[k]["who"]], "gain_db": lines[k].get("gain_db", 0)})
    t = start + d
    if k == "L5":
        T["PEEL"] = [round(t + 0.5, 3), round(t + 2.0, 3)]
FLIP = round(t + 0.7, 3)
DUR = round(FLIP + 2.4, 2)
# subtitles: from just before the line to the next line (never overlapping), at least 1.2 s
for i, v in enumerate(VO):
    v["s0"] = round(max(0.0, v["t"] - 0.08), 3)
    nxt = VO[i + 1]["t"] - 0.12 if i + 1 < len(VO) else DUR - 0.3
    v["s1"] = round(min(nxt, max(v["t"] + v["dur"] + 0.45, v["s0"] + 1.2)), 3)
    assert v["s1"] >= v["t"] + v["dur"] - 0.05, v["id"]
for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"])
assert 40 <= DUR <= 75, DUR
V = {v["id"]: v for v in VO}
end = lambda k: V[k]["t"] + V[k]["dur"]
SHOTS = [
    ["VOID", 0.0, V["L1"]["t"]],
    ["WIDE", V["L1"]["t"], V["L2"]["t"] + 0.35],
    ["POV", V["L2"]["t"] + 0.35, V["L2"]["t"] + 2.1],
    ["PIP_GLASS", V["L2"]["t"] + 2.1, V["L3"]["t"]],
    ["RAE_MED", V["L3"]["t"], V["L4"]["t"]],
    ["PIP_GLASS", V["L4"]["t"], V["L5"]["t"]],
    ["RAE_CU", V["L5"]["t"], end("L5") + 0.35],
    ["PIP_PEEL", end("L5") + 0.35, V["L6"]["t"]],
    ["MAGS_CU", V["L6"]["t"], V["L7"]["t"]],
    ["PIP_CU", V["L7"]["t"], V["L8"]["t"] - 0.5],
    ["MAGS_CU", V["L8"]["t"] - 0.5, T["FREEZE"][0]],
    ["WIDE_FREEZE", T["FREEZE"][0], T["MONSTER"]],
    ["WIDE_MONSTER", T["MONSTER"], V["L9"]["t"]],
    ["RAE_MED", V["L9"]["t"], V["L10"]["t"]],
    ["PIP_TINY", V["L10"]["t"], V["L11"]["t"]],
    ["MAGS_CU", V["L11"]["t"], FLIP - 0.4],
    ["BOARD", FLIP - 0.4, DUR],
]
SHOTS = [[n, round(a, 3), round(b, 3)] for n, a, b in SHOTS]
for a, b in zip(SHOTS, SHOTS[1:]):
    assert abs(a[2] - b[1]) < 1e-6 and a[2] > a[1], (a, b)
TL = {"BPM": BPM, "BEAT": BEAT, "BAR": BAR, "DUR": DUR, "VO": VO, "SHOTS": SHOTS, "FLIP": FLIP, **T}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
# per-line character timings for lip sync
CH = {k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["chars"] for k in V}
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\nwindow.CHARS = " + json.dumps(CH) + ";\n")
print("DUR", DUR)
for v in VO:
    print(f'{v["id"]:4} {v["who"]:4} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
for s in SHOTS: print(f'  {s[0]:13s} {s[1]:6.2f}-{s[2]:6.2f}')
