"""Single source of truth for timing: writes timeline.js (for the page) and out/timeline.json (for score, mix, srt).
  .venv/bin/python tools/timeline.py
Volt Labs 2 "The Obedience Ray": everyone will do exactly what Vera says. It makes the whole street unbearably polite.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BPM = 132.0
BEAT = 60.0 / BPM
cfg = json.load(open(os.path.join(HERE, "voice", "lines.json")))
lines = {l["id"]: l for l in cfg["lines"]}
order = [l["id"] for l in cfg["lines"]]
durs = json.load(open(os.path.join(HERE, "voice", "out", "durations.json")))
SUBCOL = {"VERA": "#d8ff7a", "CLEO": "#c9b8ff", "MAN": "#ffd9a8", "WOMAN": "#ffc4d6", "LANDLORD": "#b8e0ff"}
OUTSIDE = {"MAN", "WOMAN", "LANDLORD"}                  # heard through the window or the door: muffled in the mix
GAP = {"L1": 0.6, "L2": 0.3, "L3": 0.35, "L4": 0.4, "L5": 1.25, "L6": 1.0, "L7": 0.3, "L8": 0.4, "L9": 1.0,
       "L10": 0.35, "L11": 0.3, "L12": 0.35, "L13": 1.9, "L14": 0.5}
VO, t, T = [], 0.0, {}
for k in order:
    start = t + GAP[k]
    if k == "L5": T["FIRE"] = round(t + 0.1, 3)                      # right after "one!"
    if k == "L6": T["BUMP"] = round(t + 0.3, 3)                      # two passers-by stop nose to nose outside the window
    if k == "L9": T["KNEEL"] = round(t + 0.3, 3)                     # the gentleman kneels: his face appears in the window
    if k == "L13": T["DUCK"] = round(t + 0.15, 3); T["KNOCK"] = round(t + 0.9, 3)
    d = durs[k]
    VO.append({"id": k, "who": lines[k]["who"], "t": round(start, 3), "dur": d, "sub": lines[k].get("sub", lines[k]["text"]),
               "col": SUBCOL[lines[k]["who"]], "gain_db": lines[k].get("gain_db", 0), **({"fx": "outside"} if lines[k]["who"] in OUTSIDE else {})})
    t = start + d
T["BOARDT"] = round(t + 0.3, 3)
END_BEAT = 2.0
DUR = round(t + END_BEAT, 2)
for i, v in enumerate(VO):
    v["s0"] = round(max(0.0, v["t"] - 0.08), 3)
    nxt = VO[i + 1]["t"] - 0.12 if i + 1 < len(VO) else DUR - 0.3
    v["s1"] = round(min(nxt, max(v["t"] + v["dur"] + 0.45, v["s0"] + 1.0)), 3)
    assert v["s1"] >= v["t"] + v["dur"] - 0.05, v["id"]
for a, b in zip(VO, VO[1:]):
    assert a["s1"] < b["s0"], (a["id"], b["id"])
assert 40 <= DUR <= 62, DUR
V = {v["id"]: v for v in VO}
end = lambda k: V[k]["t"] + V[k]["dur"]
SHOTS = [
    ["WIDE_IN", 0.0, V["L2"]["t"]],
    ["CLEO_CU", V["L2"]["t"], V["L3"]["t"]],
    ["RAY_SHOT", V["L3"]["t"], V["L4"]["t"]],
    ["VERA_COUNT", V["L4"]["t"], T["FIRE"]],
    ["WIDE_FIRE", T["FIRE"], V["L5"]["t"]],
    ["VERA_CU", V["L5"]["t"], T["BUMP"] - .3],
    ["WINDOW", T["BUMP"] - .3, V["L8"]["t"]],
    ["VERA_CU", V["L8"]["t"], T["KNEEL"] - .1],
    ["WINDOW", T["KNEEL"] - .1, V["L10"]["t"]],
    ["CLEO_CU", V["L10"]["t"], V["L11"]["t"]],
    ["VERA_CU", V["L11"]["t"], V["L12"]["t"]],
    ["WINDOW", V["L12"]["t"], T["DUCK"]],
    ["WIDE_DUCK", T["DUCK"], V["L14"]["t"]],
    ["CLEO_CU", V["L14"]["t"], T["BOARDT"] - .1],
    ["BOARD", T["BOARDT"] - .1, DUR],
]
SHOTS = [[n, round(a, 3), round(b, 3)] for n, a, b in SHOTS]
for a, b in zip(SHOTS, SHOTS[1:]):
    assert abs(a[2] - b[1]) < 1e-6 and a[2] > a[1], (a, b)
TL = {"BPM": BPM, "BEAT": BEAT, "BAR": 4 * BEAT, "DUR": DUR, "VO": VO, "SHOTS": SHOTS, **T}
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
json.dump(TL, open(os.path.join(HERE, "out", "timeline.json"), "w"), indent=1)
CH = {k: json.load(open(os.path.join(HERE, "voice", "out", k + ".json")))["chars"] for k in V}
open(os.path.join(HERE, "timeline.js"), "w").write("// generated by tools/timeline.py: do not edit\nwindow.TL = " + json.dumps(TL) + ";\nwindow.CHARS = " + json.dumps(CH) + ";\n")
print("DUR", DUR, {k: T[k] for k in T})
for v in VO:
    print(f'{v["id"]:4} {v["who"]:8} {v["t"]:6.2f}-{v["t"] + v["dur"]:6.2f}  sub {v["s0"]:6.2f}-{v["s1"]:6.2f}  {v["sub"]!r}')
for s in SHOTS: print(f'  {s[0]:12s} {s[1]:6.2f}-{s[2]:6.2f}')
